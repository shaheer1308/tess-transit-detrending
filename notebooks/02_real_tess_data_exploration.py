import lightkurve as lk
import numpy as np
import pandas as pd
import matplotlib

print("Lightkurve:", lk.__version__)
print("NumPy:", np.__version__)
print("Pandas:", pd.__version__)
print("Matplotlib:", matplotlib.__version__)

search_result = lk.search_lightcurve("WASP-18", mission="TESS", author="SPOC", exptime=120)
print(search_result)

lc_sap = search_result[0].download(flux_column="sap_flux")
lc_pdcsap = search_result[0].download(flux_column="pdcsap_flux")

print(search_result[0])
print("Points (SAP):  ", len(lc_sap))
print("Points (PDCSAP):", len(lc_pdcsap))

lc_sap.plot()
lc_pdcsap.plot()

sap_clean = lc_sap.remove_nans().normalize()
pdcsap_clean = lc_pdcsap.remove_nans().normalize()

print("SAP points before:", len(lc_sap), "after:", len(sap_clean))
print("PDCSAP points before:", len(lc_pdcsap), "after:", len(pdcsap_clean))
print("Time range (days):", round(sap_clean.time.value.min(), 2), "to", round(sap_clean.time.value.max(), 2))
print("Median flux after normalizing:", round(float(np.median(sap_clean.flux.value)), 5))

ax = sap_clean.plot(color="tab:red", alpha=0.6, label="SAP (raw)")
pdcsap_clean.plot(ax=ax, color="black", alpha=0.6, label="PDCSAP")
ax.legend()